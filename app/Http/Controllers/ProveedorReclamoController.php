<?php

namespace App\Http\Controllers;

use App\Http\Requests\ProveedorReclamoReposicionRequest;
use App\Http\Requests\ProveedorReclamoLineaRequest;
use App\Http\Requests\ProveedorReclamoResolucionRequest;
use App\Http\Requests\ProveedorReclamoStoreRequest;
use App\Models\Compra;
use App\Models\ProveedorReclamo;
use App\Models\ProveedorReclamoItem;
use App\Models\ProveedorReclamoResolucion;
use App\Services\Compras\ProveedorReclamoException;
use App\Services\Compras\ProveedorReclamoService;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Str;
use Illuminate\View\View;

class ProveedorReclamoController extends Controller
{
    public function __construct(
        private readonly ProveedorReclamoService $service
    ) {}

    public function store(Compra $compra, ProveedorReclamoStoreRequest $request): RedirectResponse
    {
        try {
            $reclamo = $this->service->crearBorrador(
                $compra,
                $request->user(),
                $request->validated('lineas'),
                $request->validated('referencia_proveedor'),
                $request->validated('observacion')
            );

            return redirect()
                ->route('compras.reclamos.show', [$compra, $reclamo])
                ->with('success', 'Reclamo creado en borrador.');
        } catch (ProveedorReclamoException $exception) {
            return back()->withInput()->with('danger', $exception->getMessage());
        }
    }

    public function show(Compra $compra, ProveedorReclamo $reclamo): View
    {
        $this->assertClaimBelongsToPurchase($compra, $reclamo);
        $detalle = $this->service->detalleParaReclamo($reclamo);
        abort_unless($detalle !== null, 404);

        $reposicionKeys = [];
        foreach ($detalle['lineas'] as $linea) {
            foreach ($linea['resoluciones'] as $resolucion) {
                $modelo = $resolucion['modelo'];
                if (
                    $modelo->tipo_resolucion === ProveedorReclamoResolucion::TIPO_REPOSICION
                    && $modelo->estado !== ProveedorReclamoResolucion::ESTADO_RESUELTA
                    && $modelo->estado !== ProveedorReclamoResolucion::ESTADO_CANCELADA
                ) {
                    // Generated by the server and rendered once in the form. A
                    // retry of that form therefore remains idempotent.
                    $reposicionKeys[$modelo->id] = (string) Str::uuid();
                }
            }
        }

        return view('compra.reclamos.show', [
            'compra' => $compra->loadMissing('proveedor'),
            'reclamo' => $detalle['modelo'],
            'lineas' => $detalle['lineas'],
            'eventos' => $detalle['eventos'],
            'incidenciasReclamables' => $this->service->resumenParaCompra($compra)['incidencias_reclamables'],
            'reposicionKeys' => $reposicionKeys,
            'estadoLabels' => $this->estadoLabels(),
        ]);
    }

    public function agregarLinea(
        Compra $compra,
        ProveedorReclamo $reclamo,
        ProveedorReclamoLineaRequest $request
    ): RedirectResponse {
        return $this->runClaimAction($compra, $reclamo, function () use ($reclamo, $request): void {
            $this->service->agregarLinea($reclamo, $request->user(), $request->validated());
        }, 'Línea agregada al reclamo.');
    }

    public function enviar(Compra $compra, ProveedorReclamo $reclamo, Request $request): RedirectResponse
    {
        return $this->runClaimAction($compra, $reclamo, function () use ($reclamo, $request): void {
            $this->service->marcarEnviado($reclamo, $request->user(), $request->input('observacion'));
        }, 'Reclamo enviado al proveedor.');
    }

    public function gestion(Compra $compra, ProveedorReclamo $reclamo, Request $request): RedirectResponse
    {
        return $this->runClaimAction($compra, $reclamo, function () use ($reclamo, $request): void {
            $this->service->marcarEnGestion($reclamo, $request->user(), $request->input('observacion'));
        }, 'Reclamo marcado en gestión.');
    }

    public function cancelar(Compra $compra, ProveedorReclamo $reclamo, Request $request): RedirectResponse
    {
        $request->validate(['motivo' => ['required', 'string', 'max:2000']]);

        return $this->runClaimAction($compra, $reclamo, function () use ($reclamo, $request): void {
            $this->service->cancelarReclamo($reclamo, $request->user(), $request->string('motivo')->toString());
        }, 'Reclamo cancelado.');
    }

    public function cancelarLinea(
        Compra $compra,
        ProveedorReclamo $reclamo,
        ProveedorReclamoItem $linea,
        Request $request
    ): RedirectResponse {
        $request->validate(['motivo' => ['required', 'string', 'max:2000']]);
        $this->assertLineBelongsToClaim($reclamo, $linea);

        return $this->runClaimAction($compra, $reclamo, function () use ($linea, $request): void {
            $this->service->cancelarLinea($linea, $request->user(), $request->string('motivo')->toString());
        }, 'Línea cancelada.');
    }

    public function registrarResolucion(
        Compra $compra,
        ProveedorReclamo $reclamo,
        ProveedorReclamoItem $linea,
        ProveedorReclamoResolucionRequest $request
    ): RedirectResponse {
        $this->assertLineBelongsToClaim($reclamo, $linea);

        return $this->runClaimAction($compra, $reclamo, function () use ($linea, $request): void {
            $data = $request->validated();
            $this->service->registrarResolucion(
                $linea,
                $request->user(),
                $data['tipo_resolucion'],
                $data['cantidad'],
                $data['referencia'] ?? null,
                $data['observacion'] ?? null,
                $data['importe'] ?? null,
                $data['moneda'] ?? null
            );
        }, 'Resolución registrada en estado pendiente.');
    }

    public function resolverResolucion(
        Compra $compra,
        ProveedorReclamo $reclamo,
        ProveedorReclamoResolucion $resolucion,
        Request $request
    ): RedirectResponse {
        $this->assertResolutionBelongsToClaim($reclamo, $resolucion);

        return $this->runClaimAction($compra, $reclamo, function () use ($resolucion, $request): void {
            $this->service->marcarResolucionResuelta(
                $resolucion,
                $request->user(),
                $request->input('observacion')
            );
        }, 'Resolución confirmada.');
    }

    public function cancelarResolucion(
        Compra $compra,
        ProveedorReclamo $reclamo,
        ProveedorReclamoResolucion $resolucion,
        Request $request
    ): RedirectResponse {
        $request->validate(['motivo' => ['required', 'string', 'max:2000']]);
        $this->assertResolutionBelongsToClaim($reclamo, $resolucion);

        return $this->runClaimAction($compra, $reclamo, function () use ($resolucion, $request): void {
            $this->service->cancelarResolucion(
                $resolucion,
                $request->user(),
                $request->string('motivo')->toString()
            );
        }, 'Resolución cancelada.');
    }

    public function recibirReposicion(
        Compra $compra,
        ProveedorReclamo $reclamo,
        ProveedorReclamoResolucion $resolucion,
        ProveedorReclamoReposicionRequest $request
    ): RedirectResponse {
        $this->assertResolutionBelongsToClaim($reclamo, $resolucion);

        return $this->runClaimAction($compra, $reclamo, function () use ($resolucion, $request): void {
            $data = $request->validated();
            $this->service->recibirReposicion(
                $resolucion,
                $request->user(),
                $data['cantidad_aceptada'],
                $data['cantidad_danada'],
                $data['cantidad_incorrecta'],
                $data['idempotency_key'],
                $data['observacion'] ?? null
            );
        }, 'Llegada de reposición registrada.');
    }

    /** @return array<string,string> */
    private function estadoLabels(): array
    {
        return [
            ProveedorReclamo::ESTADO_BORRADOR => 'Borrador',
            ProveedorReclamo::ESTADO_ENVIADO => 'Enviado',
            ProveedorReclamo::ESTADO_EN_GESTION => 'En gestión',
            ProveedorReclamo::ESTADO_RESUELTO => 'Resuelto',
            ProveedorReclamo::ESTADO_CANCELADO => 'Cancelado',
        ];
    }

    private function runClaimAction(
        Compra $compra,
        ProveedorReclamo $reclamo,
        callable $action,
        string $success
    ): RedirectResponse {
        $this->assertClaimBelongsToPurchase($compra, $reclamo);

        try {
            $action();
            return redirect()->route('compras.reclamos.show', [$compra, $reclamo])->with('success', $success);
        } catch (ProveedorReclamoException $exception) {
            return back()->withInput()->with('danger', $exception->getMessage());
        }
    }

    private function assertClaimBelongsToPurchase(Compra $compra, ProveedorReclamo $reclamo): void
    {
        abort_unless((int) $reclamo->compra_id === (int) $compra->id, 404);
    }

    private function assertLineBelongsToClaim(ProveedorReclamo $reclamo, ProveedorReclamoItem $linea): void
    {
        abort_unless((int) $linea->proveedor_reclamo_id === (int) $reclamo->id, 404);
    }

    private function assertResolutionBelongsToClaim(
        ProveedorReclamo $reclamo,
        ProveedorReclamoResolucion $resolucion
    ): void {
        $resolucion->loadMissing('reclamoItem');
        abort_unless(
            $resolucion->reclamoItem
            && (int) $resolucion->reclamoItem->proveedor_reclamo_id === (int) $reclamo->id,
            404
        );
    }
}
